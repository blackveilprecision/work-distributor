// Writes Formula/wd.rb for a release: `bun scripts/formula.ts <version> <SHA256SUMS>`. The release workflow runs it after
// uploading the binaries, so `brew install` fetches exactly those files.
import { readFileSync } from "node:fs";

const [version, sumsFile] = process.argv.slice(2);
if (!/^\d+\.\d+\.\d+$/.test(version ?? "") || !sumsFile) throw new Error("usage: bun scripts/formula.ts <x.y.z> <SHA256SUMS>");
const sums = Object.fromEntries(readFileSync(sumsFile, "utf8").trim().split("\n").map((l) => l.trim().split(/\s+/).reverse()));
const repo = process.env.WD_REPO ?? "blackveilprecision/work-distributor";
const asset = (os: string, arch: string) => {
  const name = `wd-${os}-${arch}`;
  if (!/^[0-9a-f]{64}$/.test(sums[name] ?? "")) throw new Error(`no sha256 for ${name} in ${sumsFile}`);
  return `      url "https://github.com/${repo}/releases/download/v${version}/${name}"\n      sha256 "${sums[name]}"`;
};

process.stdout.write(`# Generated by scripts/formula.ts in the release workflow; do not edit by hand.
class Wd < Formula
  desc "Queue that runs Claude Code threads across hosts and reports back"
  homepage "https://github.com/${repo}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${asset("darwin", "arm64")}
    end
    on_intel do
${asset("darwin", "x64")}
    end
  end

  on_linux do
    on_arm do
${asset("linux", "arm64")}
    end
    on_intel do
${asset("linux", "x64")}
    end
  end

  def install
    binary = Dir["wd-*"].first
    chmod 0755, binary
    bin.install binary => "wd"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/wd --version").strip
  end
end
`);
